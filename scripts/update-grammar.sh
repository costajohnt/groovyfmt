#!/usr/bin/env bash
# Replace grammar/ with the files groovyfmt builds from, taken from a tree-sitter-groovy
# checkout at <rev> (default: its HEAD). Usage: scripts/update-grammar.sh <checkout> [rev]
# The checkout must be clean. Files are read from the commit with git archive, so the
# checkout's HEAD and working tree are left alone.
set -euo pipefail
[ $# -ge 1 ] && [ $# -le 2 ] || { echo "usage: $0 <grammar-checkout> [rev]" >&2; exit 2; }
src=$(cd "$1" && pwd)
rev=${2:-HEAD}
cd "$(dirname "$0")/.."

if [ -n "$(git -C "$src" status --porcelain)" ]; then
  echo "$src has uncommitted changes; commit or clean them first" >&2
  exit 1
fi
sha=$(git -C "$src" rev-parse --verify --quiet "$rev^{commit}") || { echo "no commit $rev in $src" >&2; exit 1; }
date=$(git -C "$src" show -s --format=%cs "$sha")

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
git -C "$src" archive "$sha" src/parser.c src/scanner.c src/node-types.json src/tree_sitter \
  grammar.js LICENSE-APACHE LICENSE-MIT | tar -x -C "$tmp"
rm -rf grammar
mkdir grammar
mv "$tmp"/src/* "$tmp"/grammar.js "$tmp"/LICENSE-APACHE "$tmp"/LICENSE-MIT grammar/
echo "$sha" > grammar/REV

cat > grammar/README.md <<EOF
# Vendored tree-sitter grammar

The Groovy grammar groovyfmt parses with, copied by \`scripts/update-grammar.sh\` from
[costajohnt/tree-sitter-groovy](https://github.com/costajohnt/tree-sitter-groovy) at commit
\`$sha\` ($date, branch \`groovyfmt-base\`). That fork is
[dekobon/tree-sitter-groovy](https://github.com/dekobon/tree-sitter-groovy) (Elijah Zupancic)
plus fixes made for groovyfmt; most of them are open as pull requests there. \`REV\` holds the
same commit for scripts.

| file | what it is |
|---|---|
| \`parser.c\`, \`tree_sitter/*.h\` | generated by \`tree-sitter generate\` from \`grammar.js\` |
| \`scanner.c\` | the hand-written external scanner |
| \`node-types.json\` | generated list of node kinds and fields |
| \`grammar.js\` | the grammar's source, for reading; it is not built here |
| \`LICENSE-APACHE\`, \`LICENSE-MIT\` | the grammar's licenses |

\`build.rs\` compiles \`parser.c\` and \`scanner.c\` with the flags of the grammar crate's own
build script. The files are copies: don't edit them here.

## Updating

1. Change \`grammar.js\` or \`src/scanner.c\` in a tree-sitter-groovy checkout, run
   \`tree-sitter generate\` and its tests, and commit.
2. \`scripts/update-grammar.sh <checkout> [rev]\` (rev defaults to the checkout's HEAD; the
   checkout must be clean). It replaces this directory and records the commit.
3. Run \`scripts/ci-local.sh <corpus-dir>\` and compare \`--stats\` and \`--lint\` output with
   the previous grammar.

## License

The grammar is licensed under either of the Apache License, Version 2.0 (\`LICENSE-APACHE\`) or
the MIT license (\`LICENSE-MIT\`), at your option. groovyfmt uses it under the MIT license.
EOF
echo "grammar/ now holds $sha"
