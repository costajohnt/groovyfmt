#!/usr/bin/env python3
"""Regenerates src/codenarc_data.rs, the CodeNarc rule tables `--import-codenarc` reads.

Usage: scripts/codenarc-data.py <CodeNarc checkout> <npm-groovy-lint package dir> > src/codenarc_data.rs
then `cargo fmt`. The CodeNarc checkout is https://github.com/CodeNarc/CodeNarc at the
release to record; the npm-groovy-lint directory is the installed package
(node_modules/npm-groovy-lint). Reads files only and runs nothing from either.
"""

import json
import re
import subprocess
import sys
from pathlib import Path


def strip_json_comments(s):
    # npm-groovy-lint strips // and /* */ comments; its own presets have none, but be safe
    out, i, in_str = [], 0, False
    while i < len(s):
        c = s[i]
        if in_str:
            out.append(c)
            if c == "\\":
                out.append(s[i + 1])
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
            out.append(c)
        elif s.startswith("//", i):
            i = s.find("\n", i)
            i = len(s) if i < 0 else i
            continue
        elif s.startswith("/*", i):
            i = s.index("*/", i) + 2
            continue
        else:
            out.append(c)
        i += 1
    return "".join(out)


def off(v):
    # codenarc-factory.js: "off", severity "off", disabled true or enabled false
    if v == "off":
        return True
    return isinstance(v, dict) and (
        v.get("severity") == "off" or v.get("disabled") is True or v.get("enabled") is False
    )


def main():
    cn, ngl = Path(sys.argv[1]), Path(sys.argv[2])
    res = cn / "src/main/resources"
    version = (res / "codenarc-version.txt").read_text().strip()
    commit = subprocess.run(
        ["git", "-C", str(cn), "rev-parse", "--short", "HEAD"], capture_output=True, text=True
    ).stdout.strip()
    ngl_version = json.loads((ngl / "package.json").read_text())["version"]

    by_class, typed = {}, {}

    def add(cls):
        # the file declaring the class (some files declare several), and the rule's `name`
        pkg, simple = cls.rsplit(".", 1)
        texts = [p.read_text() for p in (cn / "src/main/groovy" / pkg.replace(".", "/")).glob("*.groovy")]
        src = next(t for t in texts if re.search(rf"\bclass\s+{simple}\b", t))
        src = src[re.search(rf"\bclass\s+{simple}\b", src).start() :]
        name = re.search(r"String\s+name\s*=\s*['\"](\w+)['\"]", src).group(1)
        by_class[cls] = name
        if re.sub("Rule$", "", simple) != name:
            # src/codenarc.rs finds a <rule class> by its class name
            sys.exit(f"{cls}: rule name {name} isn't the class name without Rule")
        # a rule that runs after CodeNarc's CONVERSION phase needs the compiled classpath
        typed[name] = bool(re.search(r"compilerPhase\s*=\s*Phases\.(?!CONVERSION)", src))

    # every rule CodeNarc registers by name, and every rule in a bundled ruleset
    for line in (res / "codenarc-base-rules.properties").read_text().splitlines():
        m = re.match(r"\s*\w+\s*=\s*([\w.]+)\s*$", line)
        if m:
            add(m.group(1))
    for f in (res / "rulesets").glob("*.xml"):
        for cls in re.findall(r"<rule\s+class=['\"]([\w.]+)['\"]", f.read_text()):
            if cls not in by_class:
                add(cls)

    rulesets = []
    for f in sorted((res / "rulesets").glob("*.xml")):
        x = f.read_text()
        members = []
        for m in re.finditer(r"<rule\s+class=['\"]([\w.]+)['\"]\s*(/>|>(.*?)</rule>)", x, re.S):
            cls, body = m.group(1), m.group(3) or ""
            disabled = re.search(r"name=['\"]enabled['\"]\s+value=['\"]false['\"]", body)
            members.append((by_class[cls], not disabled))
        if "<ruleset-ref" in x or "<rule-script" in x:
            sys.exit(f"{f.name}: nested references are not supported by this script")
        rulesets.append((f"rulesets/{f.name}", members))

    presets = []
    for f in sorted((ngl / "lib").glob(".groovylintrc-*.json")):
        d = json.loads(strip_json_comments(f.read_text()))
        ext = d.get("extends", [])
        ext = [ext] if isinstance(ext, str) else ext
        rules = []
        for k, v in d.get("rules", {}).items():
            name = k.split(".")[-1]
            if name not in typed:
                print(f"{f.name}: {name} is not a CodeNarc {version} rule, dropped", file=sys.stderr)
                continue
            rules.append((name, not off(v)))
        presets.append((f.name[len(".groovylintrc-") : -len(".json")], ext, rules))

    print(f"//! Generated by scripts/codenarc-data.py from CodeNarc {version} (commit {commit}) and")
    print(f"//! npm-groovy-lint {ngl_version}. Don't edit it by hand; rerun the script.")
    print()
    print(f'pub const CODENARC_VERSION: &str = "{version}";')
    print(f'pub const NPM_GROOVY_LINT_VERSION: &str = "{ngl_version}";')
    print()
    print("/// Every CodeNarc rule by name, and whether CodeNarc compiles the code to run it.")
    print("pub const RULES: &[(&str, bool)] = &[")
    for name in sorted(typed):
        print(f'    ("{name}", {str(typed[name]).lower()}),')
    print("];")
    print()
    print("/// CodeNarc's bundled rulesets: each rule in it and whether the ruleset enables it.")
    print("pub const RULESETS: &[(&str, &[(&str, bool)])] = &[")
    for path, members in rulesets:
        print(f'    ("{path}", &[')
        for name, on in members:
            print(f'        ("{name}", {str(on).lower()}),')
        print("    ]),")
    print("];")
    print()
    print("/// npm-groovy-lint's presets for `extends`: the presets each extends, then each rule and")
    print("/// whether it is on.")
    print("pub type Preset = (&'static str, &'static [&'static str], &'static [(&'static str, bool)]);")
    print("pub const PRESETS: &[Preset] = &[")
    for name, ext, rules in presets:
        print(f'    ("{name}", &[{", ".join(json.dumps(e) for e in ext)}], &[')
        for r, on in rules:
            print(f'        ("{r}", {str(on).lower()}),')
        print("    ]),")
    print("];")


main()
